# Moves whatever is scrolling on screen to a place, in points from its top.
SCROLL = """(top) => {
  for (const each of document.querySelectorAll('*')) {
    const flow = getComputedStyle(each).overflowY;
    if ((flow === 'auto' || flow === 'scroll') && each.scrollHeight > each.clientHeight + 4 && each.offsetParent !== null) each.scrollTop = top;
  }
}"""

